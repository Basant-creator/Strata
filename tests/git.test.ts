import { describe, it, expect } from 'vitest';
import { GitClient } from '../src/git/git.js';

describe('Git Integration & Trailer Parser', () => {
  const client = new GitClient(process.cwd());

  it('detects Git repository status', () => {
    expect(GitClient.isGitRepo(process.cwd())).toBe(true);
  });

  it('parses explicit Assisted-by trailer with model', () => {
    const message = `feat: implement webhook deduplication\n\nAssisted-by: Claude Code (claude-3-7-sonnet)\nCo-authored-by: Basant <basant@example.com>`;
    const parsed = client.parseAgentAttribution(message);

    expect(parsed.confidence).toBe('DECLARED');
    expect(parsed.agent?.name).toBe('Claude Code');
    expect(parsed.agent?.model).toBe('claude-3-7-sonnet');
  });

  it('parses Co-authored-by bot trailer', () => {
    const message = `fix: resolve race condition in token refresh\n\nCo-authored-by: GitHub Copilot <copilot@github.com>`;
    const parsed = client.parseAgentAttribution(message);

    expect(parsed.confidence).toBe('DECLARED');
    expect(parsed.agent?.name).toBe('GitHub Copilot');
  });

  it('infers agent when mentioned in commit body', () => {
    const message = `refactor: optimize database query generated by Cursor`;
    const parsed = client.parseAgentAttribution(message);

    expect(parsed.confidence).toBe('INFERRED');
    expect(parsed.agent?.name).toBe('Cursor');
  });

  it('returns UNKNOWN when no agent is mentioned', () => {
    const message = `chore: update dependencies and clean scripts`;
    const parsed = client.parseAgentAttribution(message);

    expect(parsed.confidence).toBe('UNKNOWN');
    expect(parsed.agent).toBeUndefined();
  });
});
